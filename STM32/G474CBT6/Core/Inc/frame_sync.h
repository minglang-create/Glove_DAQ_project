/**
  ******************************************************************************
  * @file    frame_sync.h
  * @brief   帧节拍源与 XVS 线控制（V4：运行时可切主/从/强制电平）
  *
  * ============================================================================
  * V4 架构：XVS 是一条开漏"线与"总线，PB10 = TIM2_CH3（AF 开漏）
  * ============================================================================
  *   两手套之间只有一条线：PB10，经互连 Type-C 的 SBU 芯直连对侧 PB10，
  *   同一网络也接着本侧相机的 XVS 输入。TIM2_CH3 运行时在四种用法间切换：
  *     ① 主机放号   输出比较 toggle，硬件在 CCR3 精确时刻翻引脚（零抖动），
  *                  下降沿 = 同步沿；10us 低脉宽由迟到防护兜底（见 .c）
  *     ② 从机收号   输入捕获下降沿，CCR3 = 硬件锁存的同步沿时刻
  *     ③ 强制拉低   角色信令：主机上任宣告 2s / 从机自检应答 500ms ——
  *                  都发生在相机锁相"投产"之前，锁相后的 XVS 波形纯净
  *     ④ 释放       空闲/重新自检
  *   锁相之后线上不允许任何信令 → 开采/停采不走线，由两只手套各自的
  *   RV（各自按键）用事务包通知各自的 STM32。
  *   谁当主机由 glove_fsm 的角色分配流程在运行时决定，本模块只提供机构。
  *
  * ============================================================================
  * 边沿语义（接口约定）
  * ============================================================================
  *   开漏线空闲为高。**下降沿 = 同步沿**（主动驱动，陡峭）；上拉回弹的
  *   上升沿慢且抖，不允许作基准。脉冲：拉低 FRAME_SYNC_PULSE_LOW_US 后释放。
  *
  * ============================================================================
  * 时基
  * ============================================================================
  *   TIM2: 32 位，PSC=159 → 1MHz（1us/计数），自由运行，全局时间戳。
  *   周期三拍抖动 16667/16667/16666 → 平均精确 60.000Hz。
  ******************************************************************************
  */

#ifndef FRAME_SYNC_H
#define FRAME_SYNC_H

#include <stdint.h>

/* ==========================================================================
 * 配置
 * ========================================================================== */

/** 帧周期（us，TIM2 节拍）。基准 16667us，实际按 16667/16667/16666 三拍抖动
    → 平均精确 60.000Hz（消掉固定 16667 的 -20ppm 系统偏差，满足"晶振级精度"；
    单个边沿偏离理想网格 ≤0.67us，远小于 1H=7.242us，IMX415 锁相无感）。 */
#define FRAME_SYNC_PERIOD_US        16667u

/** XVS 低电平脉宽（us）。IMX415 从机同步规格：合法 7.2~15us（1~2H，
    1H=7.242us 为实测锁相基准），取整 10us。2026-09-02 定稿，别改回大值。 */
#define FRAME_SYNC_PULSE_LOW_US     7u

/** 连续多少毫秒没有节拍就判定"同步源丢失"（仅在 ExpectTicks(1) 时监测）。
    主机模式守护定时器配置自伤，从机模式守护主机停发/断线。 */
#define FRAME_SYNC_TIMEOUT_MS       50u

/* ==========================================================================
 * 状态
 * ========================================================================== */

typedef struct
{
  uint32_t sync_cnt;          /**< 累计节拍数 = 数据帧 CYCLE。MasterRun/SlaveRun
                                   时清零 → 主机第一个自产沿与从机第一个捕获沿
                                   都是 1（主机延迟放号保证从机先就位），
                                   **双方 CYCLE 同源同号**（2026-09-02 方案） */
  uint32_t sync_lost_cnt;     /**< 判定"同步源丢失"的次数                      */
  uint32_t last_ts;           /**< 最近一个同步沿的时间戳（1us）               */
  uint32_t period_us;         /**< 相邻同步沿间隔（主机模式在 16666/16667 间
                                   抖动是正常的——三拍平均 = 精确 60.000Hz）    */
  uint32_t period_min_us;
  uint32_t period_max_us;
  uint8_t  alive;             /**< 1 = 节拍正常（仅 ExpectTicks(1) 时有意义）  */
  uint8_t  mode;              /**< 当前机构模式：0 释放 1 主机 2 从机 3 强拉低 */
  uint32_t pulse_late_cnt;    /**< 迟到防护触发次数：中断没能在 10us 内排上
                                   上升沿，被迫软件释放（脉冲变宽但有界）。
                                   偶发无害；持续增长说明有中断长期霸占 CPU   */
} FrameSync_Stats_t;

extern FrameSync_Stats_t g_sync_stats;

/* ==========================================================================
 * 接口
 * ========================================================================== */

/**
 * @brief  启动 TIM2 时基（1us 自由跑，无中断）+ TIM6 1kHz 看门狗。
 *         CH3 保持释放态（线不出声）。角色机构由下面的 API 切换。
 */
void FrameSync_Init(void);

/** 读当前时间（TIM2 计数，1us，32 位自由运行）。任何上下文可调。 */
uint32_t FrameSync_Now(void);

/**
 * @brief  主机放号：CH3 切输出比较 toggle，自产 60Hz，下降沿驱动流水线。
 * @note   第一个同步沿在一个周期之后。内部会自动 ExpectTicks(1)。
 */
void FrameSync_MasterRun(void);

/**
 * @brief  从机收号：CH3 切输入捕获（下降沿，滤波 4），每个沿驱动流水线。
 * @note   内部自动 ExpectTicks(1)。主机停发后看门狗会把 alive 置 0，
 *         FSM 以此判定"暂停"。
 */
void FrameSync_SlaveRun(void);

/**
 * @brief  强制拉低 XVS 线（角色信令）。仅限相机锁相"投产"之前的阶段。
 */
void FrameSync_ForceLow(void);

/**
 * @brief  释放 XVS 线（空闲/重新自检）。停节拍、停中断，线由上拉抬高。
 */
void FrameSync_Release(void);

/** 读 XVS 线的实际电平。1=高。角色信令阶段的采样入口。 */
uint8_t FrameSync_LineIsHigh(void);

/**
 * @brief  主机放号时是否处于释放相（本机没在拉低）。
 * @note   从机应答检测用：释放相里线为低 = 从机在拉。10us 脉宽下
 *         释放相占比 99.94%，采样几乎不受自身脉冲影响。
 */
uint8_t FrameSync_OutputReleased(void);

/**
 * @brief  看门狗开关：1 = 当前状态应该有节拍（RUNNING/放号中），丢了要报；
 *         0 = 静默是正常的（自检/就绪/暂停），不监测。
 */
void FrameSync_ExpectTicks(uint8_t expect);

/**
 * @brief  节拍统一入口（主机比较事件 / 从机捕获事件都汇到这里）。
 * @param  ts  同步沿硬件时间戳（1us）
 * @note   中断上下文（TIM2 中断，优先级 0），内部调 GloveApp_OnFrameSync()。
 */
void FrameSync_Handle(uint32_t ts);

#endif /* FRAME_SYNC_H */
